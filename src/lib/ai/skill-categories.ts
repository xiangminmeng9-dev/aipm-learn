/**
 * 获取技能的分类，未匹配到的返回"未分类"
 */
export function getSkillCategory(skillName: string): string {
  return SKILL_CATEGORY_MAP[skillName] || '未分类';
}

/**
 * 获取某个分类下的所有技能
 */
export function getSkillsByCategory(category: SkillCategory): string[] {
  return Object.entries(SKILL_CATEGORY_MAP)
    .filter(([_, cat]) => cat === category)
    .map(([skill]) => skill);
}
