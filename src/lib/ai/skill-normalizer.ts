// 构建反向映射和模糊规则（懒初始化）
let _aliasToCanonical: Map<string, string> | null = null;
let _fuzzyRules: Array<{ canonical: string; keyword: string }> | null = null;

function getAliasToCanonical() {
  if (_aliasToCanonical) return _aliasToCanonical;
  _aliasToCanonical = new Map();
  for (const [canonical, aliases] of Object.entries(skillAliases)) {
    _aliasToCanonical.set(canonical.toLowerCase(), canonical);
    for (const alias of aliases) {
      _aliasToCanonical.set(alias.toLowerCase(), canonical);
    }
  }
  return _aliasToCanonical;
}

function getFuzzyRules() {
  if (_fuzzyRules) return _fuzzyRules;
  _fuzzyRules = [];
  for (const [canonical, aliases] of Object.entries(skillAliases)) {
    const allNames = [canonical, ...aliases];
    for (const name of allNames) {
      const parts = name
        .replace(/[与和及]/g, '|')
        .replace(/[（）()]/g, '|')
        .split('|')
        .map(s => s.trim())
        .filter(s => s.length >= 2);
      for (const part of parts) {
        _fuzzyRules.push({ canonical, keyword: part });
      }
    }
  }
  _fuzzyRules.sort((a, b) => b.keyword.length - a.keyword.length);
  return _fuzzyRules;
}

/**
 * 模式匹配：年限/学历/专业/价值观等模式化输入
 * 在精确匹配之前执行，避免模糊匹配误伤
 */
function matchPattern(name: string): string | null {
  // 年限经验模式
  const yearMatch = name.match(/(\d+)[-~至到]?(\d+)?年(?:以上|及以上)?(?:互联网|AI|产品经理|产品|工作|相关|运营|策略产品|数据产品|AI领域|AI方向|AI经验|基础体验专注|实战|广告或推荐相关)?(?:产品经理|产品|工作|从业|经验|实操)?/);
  if (yearMatch) {
    const min = parseInt(yearMatch[1]);
    if (name.includes('产品经理') || name.includes('策略产品') || name.includes('数据产品')) {
      if (min >= 5) return '5年以上产品经理经验';
      if (min >= 3) return '3年以上产品经理经验';
      if (min >= 2) return '2年以上产品经理经验';
      return '1年以上产品经理经验';
    }
    if (name.includes('AI') || name.includes('人工智能')) {
      if (min >= 3) return '3年以上产品经理经验';
      return '1-2年AI从业经验';
    }
    if (name.includes('运营')) return '产品经理工作经验';
    if (name.includes('工作') || name.includes('经验')) {
      if (min >= 5) return '5年以上产品经理经验';
      if (min >= 3) return '3年以上产品经理经验';
      if (min >= 2) return '2年以上产品经理经验';
      return '1年以上产品经验';
    }
    if (min >= 3) return '3年以上产品经理经验';
    return '1年以上产品经验';
  }

  // 学历模式
  if (/本科(?:及)?以上|本科学历|本科以上学历|知名高校|重点院校|985|211|统招全日制本科/.test(name)) {
    return '重点院校学历';
  }
  if (/硕士(?:及)?以上|硕士学历/.test(name)) {
    return '重点院校学历';
  }

  // 专业背景模式
  if (/计算机[与/及]?AI|计算机[与/及]?人工智能|AI[与/及]?计算机|计算机.*专业|计算机.*背景/.test(name)) {
    return '计算机相关专业';
  }
  if (/数学.*统计|统计.*数学|数学[与/及]?计算机|理工科|理工.*背景|理科.*背景|理科专业|相关专业背景|相关专业学历/.test(name)) {
    return '理工科专业';
  }
  if (/人工智能.*专业|AI.*专业|数据科学.*专业/.test(name)) {
    return '计算机相关专业';
  }
  if (/影视|艺术|视觉.*专业/.test(name)) {
    return '理工科专业';
  }
  if (/供应链.*专业|统计.*专业/.test(name)) {
    return '理工科专业';
  }

  // 英语/价值观模式
  if (/英语.*工作|英文.*工作|英语流利/.test(name)) {
    return '英文能力';
  }
  if (/价值观|京东.*价值观|拼搏.*担当/.test(name)) {
    return '企业价值观认同';
  }

  // 产品经理经验变体
  if (/互联网产品经理经验/.test(name)) {
    return '3年以上产品经理经验';
  }
  if (/产品经理工作经验?[\d年]/.test(name)) {
    return '3年以上产品经理经验';
  }
  if (/产品工作经验/.test(name)) {
    return '2年以上产品经理经验';
  }

  return null;
}

/**
 * 归一化技能名称：模式匹配 → 精确匹配 → 模糊子串匹配 → 反向匹配 → onceSkillRemap
 */
export function normalizeSkill(name: string): string {
  const lower = name.toLowerCase();

  // 0. 模式匹配：年限/学历/专业/价值观等模式化输入
  const patternResult = matchPattern(name);
  if (patternResult) return patternResult;

  // 1. 精确匹配
  const exact = getAliasToCanonical().get(lower);
  let result = exact;

  // 2. 模糊匹配：输入包含关键词（长词优先）
  if (!result) {
    for (const { canonical, keyword } of getFuzzyRules()) {
      if (lower.includes(keyword.toLowerCase())) {
        result = canonical;
        break;
      }
    }
  }

  // 3. 反向匹配：标准技能名包含输入
  if (!result) {
    for (const [canonicalName, aliases] of Object.entries(skillAliases)) {
      const allNames = [canonicalName, ...aliases];
      for (const alias of allNames) {
        if (alias.toLowerCase().includes(lower) && lower.length >= 2) {
          result = canonicalName;
          break;
        }
      }
      if (result) break;
    }
  }

  // 4. 如果以上都没匹配到，使用原始名称
  if (!result) result = name;

  // 5. 对归一化结果检查 onceSkillRemap（低频技能二次映射）
  if (onceSkillRemap[result]) {
    return onceSkillRemap[result];
  }

  return result;
}

/**
 * 混合表述拆分规则：将含多个概念的原始技能名拆为多个归一化技能
 * "与"/"和"/"及"/"/" 连接的不同概念拆开分别归一化
 */
const SPLIT_PATTERNS: Array<{ pattern: RegExp; parts: (match: RegExpMatchArray) => string[] }> = [
  // "X与Y" 拆分
  {
    pattern: /^(.+?)(与|和|及|\/|，|,)(.+)$/,
    parts: (m) => [m[1].trim(), m[3].trim()],
  },
];

/**
 * 多值归一化：一个原始技能名可能对应多个归一化技能
 * 用于图谱中来源技能→归一化技能的1对多关系
 */
export function normalizeSkillMulti(name: string): string[] {
  // 1. 先尝试整体归一化
  const primary = normalizeSkill(name);

  // 2. 尝试拆分
  const results: string[] = [primary];
  for (const { pattern, parts } of SPLIT_PATTERNS) {
    const match = name.match(pattern);
    if (match) {
      const splitParts = parts(match);
      // 只在拆分后每部分都有2个字以上时才拆
      if (splitParts.every(p => p.length >= 2)) {
        const normalizedParts = splitParts.map(p => normalizeSkill(p));
        // 如果拆分后的结果和整体不同，添加额外的归一化结果
        for (const np of normalizedParts) {
          if (!results.includes(np)) {
            results.push(np);
          }
        }
      }
      break; // 只拆一次
    }
  }

  return results;
}

/**
 * 完整的技能归一化函数（用于JD分析后处理）
 * 与 normalizeSkill 相同逻辑，但语义更明确
 */
export const remapSkill = normalizeSkill;

/**
 * 聚合技能频率（归一化后），同一条JD中同一技能只算1次
 * 返回 Map<标准技能名, { count, positions, importance? }>
 */
export function aggregateSkills(
  analyses: Array<{
    position_name?: string;
    extracted_skills?: Array<{ skill_name: string; importance?: string; category?: string }>;
  }>,
  options?: { trackPositions?: boolean; trackImportance?: boolean }
): Map<string, { count: number; positions?: string[]; importance?: string[] }> {
  const { trackPositions = true, trackImportance = true } = options ?? {};
  const skillMap = new Map<string, { count: number; positions?: string[]; importance?: string[] }>();

  for (const a of analyses) {
    const skills = a.extracted_skills || [];
    const seenInThisJd = new Set<string>();
    const posName = a.position_name || '未命名岗位';

    for (const s of skills) {
      const normalized = normalizeSkill(s.skill_name);
      if (seenInThisJd.has(normalized)) continue;
      seenInThisJd.add(normalized);

      if (!skillMap.has(normalized)) {
        skillMap.set(normalized, { count: 0, positions: trackPositions ? [] : undefined, importance: trackImportance ? [] : undefined });
      }
      const entry = skillMap.get(normalized)!;
      entry.count++;
      if (trackPositions && entry.positions) entry.positions.push(posName);
      if (trackImportance && s.importance && entry.importance) entry.importance.push(s.importance);
    }
  }

  return skillMap;
}
